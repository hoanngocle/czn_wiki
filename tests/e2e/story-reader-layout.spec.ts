import { expect, test } from "@playwright/test";

test("reader stays inside the story layout and preserves its chapter when switching views", async ({ page }) => {
  await page.goto("/ebooks/chu-gioi-tan-the-online");
  await page.getByRole("navigation", { name: "Trang trong wiki truyện" }).getByRole("link", { name: "Đọc truyện", exact: true }).click();
  await expect(page).toHaveURL(/\/ebooks\/chu-gioi-tan-the-online\/doc-truyen$/);
  await expect(page.getByRole("link", { name: "Về thư viện truyện" })).toBeVisible();
  const reader = page.frameLocator('iframe[title="Đọc Chư Giới Tận Thế Online"]');
  await reader.getByRole("link", { name: "Bắt đầu đọc →", exact: true }).click();
  await expect(reader.getByRole("heading", { name: "Chương 1: Hố người chết", exact: true })).toBeVisible();
  await expect(reader.locator(".chapter-text")).toHaveCSS("text-align", "justify");
  const header = page.getByTestId("story-header").filter({ visible: true });
  const controls = reader.locator(".chapter-controls");
  await expect(controls).toBeVisible();
  await expect(header.getByRole("button", { name: "Tăng cỡ chữ", exact: true })).toHaveCount(0);
  await expect(controls.getByRole("link", { name: /Chương trước/ })).toHaveCount(0);
  const settingsTrigger = header.getByRole("button", { name: "Cài đặt đọc truyện", exact: true });
  const settings = page.getByRole("dialog", { name: "Cài đặt đọc truyện", exact: true });
  await settingsTrigger.click();
  await settings.getByRole("button", { name: "Tăng cỡ chữ", exact: true }).click();
  await expect(settings.getByRole("status")).toHaveText("21");
  await expect(reader.locator("html")).toHaveCSS("--reading-size", "21px");
  await settings.getByRole("button", { name: "Đổi nền sáng tối", exact: true }).click();
  await expect(reader.locator("html")).toHaveAttribute("data-theme", "dark");
  await settings.getByRole("button", { name: "Đóng cài đặt", exact: true }).press("Escape");
  await expect(settings).toBeHidden();
  await expect(settingsTrigger).toBeFocused();
  await controls.getByRole("link", { name: /Chương sau/ }).click();
  await expect(reader.getByRole("heading", { name: "Chương 2: Tận thế", exact: true })).toBeVisible();
  await expect(header.getByLabel("Chương hiện tại")).toHaveValue("2");
  await expect(controls.getByRole("link", { name: /Chương trước/ })).toBeVisible();
  await expect(reader.locator("html")).toHaveCSS("--reading-size", "21px");
  await page.getByRole("navigation", { name: "Trang trong wiki truyện" }).getByRole("link", { name: "Cốt truyện", exact: true }).click();
  await expect(page.getByTestId("story-viewport")).toBeVisible();
  await page.getByRole("navigation", { name: "Trang trong wiki truyện" }).getByRole("link", { name: "Đọc truyện", exact: true }).click();
  await expect(reader.getByRole("heading", { name: "Chương 2: Tận thế", exact: true })).toBeVisible();
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect(controls.getByRole("link", { name: /Chương sau/ })).toBeVisible();
    expect(await reader.locator("html").evaluate(el => el.scrollWidth <= window.innerWidth)).toBe(true);
    const positions = await controls.locator(".chapter-nav").evaluate(nav => {
      const box = nav.getBoundingClientRect();
      const contents = nav.querySelector('[data-contents]')!.getBoundingClientRect();
      const previous = nav.querySelector('[rel="prev"]')!.getBoundingClientRect();
      const next = nav.querySelector('[rel="next"]')!.getBoundingClientRect();
      return { center: Math.abs(contents.left + contents.width / 2 - box.left - box.width / 2), left: previous.left - box.left, right: box.right - next.right };
    });
    expect(positions.center).toBeLessThan(2);
    expect(positions.left).toBeLessThan(2);
    expect(positions.right).toBeLessThan(2);
    await settingsTrigger.click();
    await expect(settings.getByRole("status")).toHaveText("21");
    await expect(settings.getByRole("button", { name: "Đổi nền sáng tối" })).toHaveAttribute("aria-pressed", "true");
    if (width === 1440 || width === 390) await page.screenshot({ path: `test-results/reader-settings-${width}.png` });
    await settings.getByRole("button", { name: "Đóng cài đặt", exact: true }).click();
    if (width === 1440 || width === 390) await page.screenshot({ path: `test-results/reader-header-${width}.png` });
  }
  await header.getByLabel("Chương hiện tại").selectOption("94");
  await expect(reader.locator("body")).toHaveAttribute("data-chapter", "94");
  await controls.getByRole("button", { name: "Mục lục", exact: true }).click();
  const dialog = reader.getByRole("dialog", { name: "Mục lục" });
  await expect(dialog).toBeVisible();
  const current = dialog.locator('[aria-current="page"]');
  await expect(current).toContainText("Chương 94:");
  const centered = await current.evaluate(el => {
    const row = el.getBoundingClientRect();
    const list = el.parentElement!.getBoundingClientRect();
    return Math.abs(row.top + row.height / 2 - list.top - list.height / 2);
  });
  expect(centered).toBeLessThan(3);
  await page.screenshot({ path: "test-results/reader-contents-mobile.png" });
  await dialog.getByLabel("Tìm chương").fill("120");
  await dialog.getByRole("link", { name: /Chương 120:/ }).click();
  await expect(reader.locator("body")).toHaveAttribute("data-chapter", "120");
  await controls.getByRole("button", { name: "Mục lục", exact: true }).click();
  await dialog.getByLabel("Tìm chương").press("Escape");
  await expect(dialog).toBeHidden();
  await expect(controls.getByRole("button", { name: "Mục lục", exact: true })).toBeFocused();
});
