import { expect, test } from "@playwright/test";

test("Renoa language checkbox switches cards and variants and remembers the choice", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/combatant/renoa");
  const card = page.getByRole("button", { name: "Echo of Sorrow card", exact: true });
  await expect(card).toContainText("Gây 140% sát thương");
  await expect(card).toContainText("Dirge Bullet");
  const vietnamese = page.getByRole("checkbox", { name: "Tiếng Việt" });
  await expect(vietnamese).toBeChecked();
  await expect(page.getByRole("complementary", { name: "Thuật ngữ Renoa" })).toHaveCount(0);
  await vietnamese.uncheck();
  await expect(card).toContainText("140% Damage");
  await card.click();
  await expect(page.getByRole("dialog")).toContainText("At the start of the turn");
  await page.getByRole("dialog").getByRole("button", { name: "Close dialog" }).click();
  await page.reload();
  await expect(vietnamese).not.toBeChecked();
  await expect(card).toContainText("140% Damage");
  await vietnamese.check();
  await card.click();
  const dialog = page.getByRole("dialog", { name: "Echo of Sorrow", exact: true });
  await expect(dialog.getByRole("button", { name: "Echo of Sorrow card", exact: true })).toHaveCount(6);
  await expect(dialog).toContainText("Đầu lượt, tạo 1 lá Dirge Bullet");
  await expect(dialog.getByRole("complementary", { name: "Thuật ngữ Renoa" })).toHaveCount(0);
  await dialog.getByRole("button", { name: "Close dialog" }).click();
  await expect(dialog).not.toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(vietnamese).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Animation" })).toBeVisible();
  await vietnamese.uncheck();
  await expect(card).toContainText("140% Damage");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test("terminology has its own navigation tab and direct route on desktop and mobile", async ({ page }) => {
  await page.goto("/combatant/renoa");
  await page.getByRole("link", { name: "Terminology", exact: true }).click();
  await expect(page).toHaveURL(/\/terminology$/);
  await expect(page.getByRole("link", { name: "Terminology", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(page.getByRole("heading", { name: "Thuật ngữ", exact: true })).toBeVisible();
  await expect(page.getByText("Critical Chance", { exact: true })).toBeVisible();
  const search = page.getByRole("searchbox", { name: "Tìm thuật ngữ" });
  const terms = page.getByRole("region", { name: "Danh sách thuật ngữ" }).locator("dt");
  await search.fill("  SHIELD  ");
  await expect(terms.filter({ hasText: /^Shield$/ })).toBeVisible();
  await expect(terms.filter({ hasText: /^HP$/ })).toHaveCount(0);
  await search.fill("ty le chi mang");
  await expect(terms).toHaveText(["Critical Chance"]);
  await search.fill("no-matching-term");
  await expect(terms).toHaveCount(0);
  await expect(page.getByText("Không tìm thấy thuật ngữ phù hợp.")).toBeVisible();
  await search.fill("");
  await expect(page.getByRole("region", { name: "Danh sách thuật ngữ" }).getByText("Shield", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(page.getByRole("heading", { name: "Thuật ngữ", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Open navigation" }).click();
  await expect(page.getByRole("link", { name: "Terminology", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test("language preference covers Manifest Ego, Potential, and all upgrade levels", async ({ page }) => {
  await page.goto("/combatant/renoa");
  const vietnamese = page.getByRole("checkbox", { name: "Tiếng Việt" });
  const ego = page.getByTestId("manifest-level");
  const potential = page.getByTestId("potential-node").filter({ hasText: "Basic Card Upgrade" });
  await expect(ego).toHaveCount(6);
  await expect(ego.nth(1)).toContainText("Cứ tạo 4 lá Dirge Bullet, tạo 1 lá Dirge Bullet: Finale.");
  await expect(ego.nth(3)).toContainText("Rose’s Resolve");
  await expect(potential).toContainText("Tăng 20% sát thương");
  await potential.click();
  const upgrades = page.getByRole("dialog", { name: "Basic Card Upgrade", exact: true });
  await expect(upgrades).toContainText("Tăng 32% sát thương");
  await upgrades.getByRole("button", { name: "Close dialog" }).click();
  await vietnamese.uncheck();
  await expect(ego.nth(1)).toContainText("For every 4 Dirge Bullet Cards created");
  await potential.click();
  await expect(upgrades).toContainText("Increase Damage, Shield Gain, and Heal Amounts of Basic Cards by 32%");
  await upgrades.getByRole("button", { name: "Close dialog" }).click();
  await vietnamese.check();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("tab", { name: "Manifest Ego", exact: true }).click();
  await expect(ego.nth(1)).toBeVisible();
  await expect(ego.nth(1)).toContainText("Cứ tạo 4 lá");
  await page.getByRole("tab", { name: "Potential", exact: true }).click();
  await potential.click();
  await expect(upgrades).toContainText("Tăng 32% sát thương");
});
