import { existsSync, readFileSync, writeFileSync } from "node:fs";
// Keep the four hand-edited guides intact while registering the released roster.
const roster = JSON.parse(readFileSync("data/wiki/characters.json", "utf8")).filter(c => c.kind === "combatant");
const legacy = { "1041": "renoa", "1033": "veronica", "1052": "narja", "30075": "sereniel" };
const guideRoster = roster.filter(c => c.source === "e7bot" || existsSync(`data/wiki/guides/${legacy[c.id] ?? c.id}.json`));
for (const { id } of roster) {
    const name = legacy[id] ?? id;
    for (const path of [`data/wiki/characters/${id}.json`, ...(guideRoster.some(c => c.id === id) ? [`data/wiki/guides/${name}.json`] : []), ...["cards", "glossary", "progression"].map(part => `data/wiki/translations/vi/${name}.${part}.json`)]) {
        if (!existsSync(path))
            throw new Error(`Missing required content: ${path}`);
    }
}
writeFileSync("data/wiki/characters/index.ts", [
    '// Generated by scripts/register-combatant-content.mjs.',
    ...roster.map(({ id }) => `import c${id} from "./${id}.json";`),
    'import type { CharacterDetail } from "../../../lib/wiki/types";',
    'export const characterDetails: Record<string, CharacterDetail> = {',
    ...roster.map(({ id }) => `  "${id}": c${id} as CharacterDetail,`),
    '};', '',
].join("\n"));
writeFileSync("data/wiki/guides/index.ts", [
    '// Generated by scripts/register-combatant-content.mjs.',
    ...guideRoster.map(({ id }) => `import g${id} from "./${legacy[id] ?? id}.json";`),
    'import { renoaEpiphanyReviews } from "./renoa-epiphany";',
    'import type { CharacterGuide } from "../../../lib/wiki/character-guide";',
    'export const characterGuides: Record<string, CharacterGuide> = {',
    ...guideRoster.map(({ id }) => `  "${id}": ${id === "1041" ? `{ ...g${id}, epiphanyReviews: renoaEpiphanyReviews } as CharacterGuide` : `g${id} as CharacterGuide`},`),
    '};', '',
].join("\n"));
writeFileSync("data/wiki/translations/index.ts", [
    '// Generated by scripts/register-combatant-content.mjs.',
    ...roster.flatMap(({ id }) => ["cards", "glossary", "progression"].map(part => `import ${part}${id} from "./vi/${legacy[id] ?? id}.${part}.json";`)),
    'import extraCards from "./vi/guide-extra.cards.json";',
    'import extraTerms from "./vi/guide-extra.terms.json";',
    'import type { Card } from "../../../lib/wiki/types";',
    'export type CharacterTranslation = {',
    '  cards: Record<string, string>;',
    '  terms: (Card["tooltips"][number] & { englishTitle?: string; englishDesc?: string })[];',
    '  manifestEgo: Record<string, string>;',
    '  potentialNodes: Record<string, string>;',
    '};',
    'export const characterTranslations: Record<string, CharacterTranslation> = {',
    ...roster.map(({ id }) => `  "${id}": { cards: ${`{ ...extraCards, ...cards${id} }`}, terms: ${`[...glossary${id}.terms, ...extraTerms]`}, ...progression${id} },`),
    '};', '',
].join("\n"));
console.log(`Registered ${roster.length} Combatants, guides and Vietnamese overlays.`);
